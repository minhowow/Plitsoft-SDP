def duty_block(d: dict) -> str:
    """질문에 넣는 의무. 요건은 조문 인용에 있는 것만이다. 의무 지도의 '지킨 모양'은 찾을 말의 예로만 준다(요건이 아니다).
    '위반 모양'은 조문 밖의 요건을 끌어들여 넣지 않는다(11/11 실측: 조문에 없는 '변경 시 재고지'로 확인할 것을 만들었다)."""
    lines = [f"- [{d['id']}] {d['law']} {d['article']} — {d['title']}", f"  의무: {d['duty']}"]
    if d.get("prohibition"):
        lines.append("  종류: 금지 의무(금지된 행위가 코드에 있는지 본다. 막는 장치가 없다는 것은 근거가 아니다)")
    for key, label in (
        ("addressee", "주체"),
        ("quote", "조문(요건은 여기 적힌 것만)"),
        ("trigger", "의무가 걸리는 신호"),
        ("compliant_shapes", "찾아볼 모양(요건이 아니라 검색할 말의 예)"),
    ):
        if d.get(key):
            lines.append(f"  {label}: {d[key]}")
    return "\n".join(lines)


def cite_lines(citations: list[dict], limit: int = 4) -> str:
    return "; ".join(f"`{c['file']}`:{c.get('line')} {str(c.get('text', ''))[:140]}" for c in citations[:limit])


def search_lines(searches: list[dict], limit: int = 4) -> str:
    return "; ".join(f"/{s['pattern']}/ {s.get('path') or '.'} → {s.get('found')}줄" for s in searches[:limit])


def parse_object(text: str, key: str) -> dict | None:
    """답에서 `key` 를 가진 JSON 객체 하나를 찾는다. 앞뒤에 글이 붙어 있어도 된다."""
    dec = json.JSONDecoder()
    start = text.find("{")
    while start != -1:
        try:
            doc, _ = dec.raw_decode(text, start)
        except json.JSONDecodeError:
            doc = None
        if isinstance(doc, dict) and key in doc:
            return doc
        start = text.find("{", start + 1)
    return None


def citations_of(item: dict) -> list[dict]:
    return [c for c in item.get("citations") or [] if isinstance(c, dict)]


def searches_of(item: dict) -> list[dict]:
    return [s for s in item.get("searches") or [] if isinstance(s, dict) and isinstance(s.get("pattern"), str)][:6]
